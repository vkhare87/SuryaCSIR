import { describe, it, expect } from 'vitest';
import { featureAccessible } from './featureControls';
import { ACCESS_MAP, ALL_ROLES, FEATURE_LABELS, type AccessPath } from '../../constants/access';

// What every role can open by default (no grants, no switches), written to
// docs/engineering/role_features.md. Changing access fails this test until the
// doc is regenerated with: npx vitest run src/lib/access/roleFeatures.test.ts -u
describe('role feature inventory', () => {
  it('matches docs/engineering/role_features.md', async () => {
    const all = Object.keys(ACCESS_MAP) as AccessPath[];
    const none = new Set<string>();
    const lines = ['# Features each role can open', '',
      'Generated by `src/lib/access/roleFeatures.test.ts` from `ACCESS_MAP`. Defaults only:',
      'MasterAdmin grants and Feature Controls switches change it per user.', ''];
    for (const role of ALL_ROLES) {
      const p = all.filter(x => featureAccessible(x, role, [], none));
      lines.push(`## ${role} — ${p.length} of ${all.length}`, '', ...p.map(x => `- ${FEATURE_LABELS[x]} \`${x}\``), '');
    }
    await expect(lines.join('\n')).toMatchFileSnapshot('../../../docs/engineering/role_features.md');
  });
});
